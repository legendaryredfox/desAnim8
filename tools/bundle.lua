-- Builds dist/desAnim8.lua, a single-file copy of the library, from desAnim8.lua
-- and desAnim8/*.lua. For targets where a multi-file require is awkward (console
-- wrappers) or when you just want one file to drop into a project.
--
--   lua tools/bundle.lua           write dist/desAnim8.lua
--   lua tools/bundle.lua --check   exit 1 when dist/desAnim8.lua is out of date
--
-- Run it from the repository root. The bundle carries its own tiny `require`, so
-- it does not touch package.path or the global require.

-- Order is only for a stable output; modules load lazily by name.
local MODULES = {
    'util', 'timing', 'options', 'events', 'playback', 'timeline', 'frameinfo', 'debug', 'render',
    'state', 'animation', 'grid', 'constructors', 'atlas', 'sheet', 'set', 'composite', 'batch',
    'watcher', 'shaders',
}

local function read(path)
    local file = assert(io.open(path, 'rb'))
    local text = file:read('*a')
    file:close()
    return text
end

local parts = {
    '-- desAnim8 single-file build. GENERATED by tools/bundle.lua from desAnim8.lua and\n' ..
    '-- desAnim8/*.lua: edit those files and rebuild, never this one.\n' ..
    '-- Requires nothing: modules are packed below and found by a private require.\n\n' ..
    'local __modules, __loaded = {}, {}\n\n' ..
    'local function require(name)\n' ..
    '    local cached = __loaded[name]\n' ..
    '    if cached ~= nil then return cached end\n' ..
    '    local loader = __modules[name]\n' ..
    "    if loader == nil then error(\"desAnim8 bundle: no module '\" .. name .. \"'\", 2) end\n" ..
    '    local result = loader(name)\n' ..
    '    if result == nil then result = true end\n' ..
    '    __loaded[name] = result\n' ..
    '    return result\n' ..
    'end\n',
}

local function add(name, path)
    local source = read(path):gsub('\n+$', '')
    parts[#parts + 1] = ("__modules['%s'] = function(...)\n%s\nend\n"):format(name, source)
end

for _, name in ipairs(MODULES) do add('desAnim8.' .. name, 'desAnim8/' .. name .. '.lua') end
add('desAnim8', 'desAnim8.lua')
parts[#parts + 1] = "return require('desAnim8')\n"

local output = table.concat(parts, '\n')

if arg and arg[1] == '--check' then
    local ok, current = pcall(read, 'dist/desAnim8.lua')
    if not ok or current ~= output then
        io.stderr:write('dist/desAnim8.lua is out of date: run lua tools/bundle.lua\n')
        os.exit(1)
    end
    io.write('dist/desAnim8.lua is up to date\n')
    return
end

local file = assert(io.open('dist/desAnim8.lua', 'wb'))
file:write(output)
file:close()
io.write(('wrote dist/desAnim8.lua (%d bytes)\n'):format(#output))
